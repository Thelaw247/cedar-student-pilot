#!/usr/bin/env node
/**
 * Writes the Supabase Auth email templates from the shared layout into
 * docs/email-templates/. Supabase's dashboard holds the live copy; this folder
 * is the versioned source — run this, then paste each file into
 * Authentication → Emails → <template> (HTML/source mode).
 *
 * The {{ .ConfirmationURL }} and {{ .Token }} placeholders are Supabase's, not
 * ours, so the layout is told not to escape them.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderEmail } from '../server/lib/emailLayout.js';

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'email-templates');

export const TEMPLATES = {
  // The code leads, and the link is the shortcut underneath it.
  //
  // A link-only confirmation looked fine and was not. Mail apps open links in
  // their OWN in-app browser, which has its own storage — so the tap signs in
  // a session the student cannot see, while the tab they signed up in sits
  // there waiting. On 6 Sep that gap cost a real signup nine and a half
  // minutes. A code carries back to the screen already in front of them, and
  // works from a laptop when the email is on a phone.
  confirmation: {
    subject: 'Confirm your Praelecta account',
    heading: 'Welcome to Praelecta',
    preheader: 'Your confirmation code is inside — six digits, valid for one hour.',
    paragraphs: [
      'Thanks for signing up. Enter this code on the confirmation screen and your account is ready — your first lecture recording is a tap away.',
    ],
    code: { label: 'Your confirmation code', value: '{{ .Token }}' },
    cta: { label: 'Or confirm with one tap', url: '{{ .ConfirmationURL }}' },
    footnote: 'The code and the link do the same thing, and either one works once. Didn&rsquo;t create a Praelecta account? You can ignore this email and nothing will happen.',
  },
  recovery: {
    subject: 'Reset your Praelecta password',
    heading: 'Reset your password',
    preheader: 'Choose a new password for your Praelecta account.',
    paragraphs: [
      'Someone asked to reset the password for this Praelecta account. If that was you, the button below opens a page where you can choose a new one. The link works once and expires in one hour.',
    ],
    cta: { label: 'Choose a new password', url: '{{ .ConfirmationURL }}' },
    footnote: 'Didn&rsquo;t ask for this? You can safely ignore this email — your password stays exactly as it is, and nobody else can use this link without access to your inbox.',
  },
  magic_link: {
    subject: 'Your Praelecta sign-in link',
    heading: 'Sign in to Praelecta',
    preheader: 'Your one-time sign-in link, valid for one hour.',
    paragraphs: [
      'Here is your one-time sign-in link. It works once and expires in one hour.',
    ],
    cta: { label: 'Sign in', url: '{{ .ConfirmationURL }}' },
    footnote: 'Didn&rsquo;t request this? Ignore this email — the link is useless to anyone without access to your inbox.',
  },
  email_change: {
    subject: 'Confirm your new email address',
    heading: 'Confirm your new email',
    preheader: 'Confirm the change to your Praelecta sign-in email.',
    paragraphs: [
      'You asked to change the email on your Praelecta account to <strong>{{ .NewEmail }}</strong>. Confirm it below and this becomes the address you sign in with.',
    ],
    cta: { label: 'Confirm new email', url: '{{ .ConfirmationURL }}' },
    footnote: 'Didn&rsquo;t ask for this? Ignore this email and your sign-in email stays as it is. If you are worried, change your password from Settings.',
  },
};

fs.mkdirSync(out, { recursive: true });
for (const [name, t] of Object.entries(TEMPLATES)) {
  const html = `<!-- Praelecta — ${t.heading} (Supabase Auth template "${name}").
     Generated by scripts/build-email-templates.mjs from server/lib/emailLayout.js — edit there, not here.
     Paste into: Supabase dashboard -> Authentication -> Emails -> ${name.replace('_', ' ')}.
     Subject line: ${t.subject} -->
${renderEmail({ ...t, rawUrls: true })}
`;
  fs.writeFileSync(path.join(out, `${name}.html`), html);
  console.log(`wrote docs/email-templates/${name}.html`);
}
